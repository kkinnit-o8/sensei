/**
 * npm run validate:words
 *
 * Checks data/words.json and writes data/words-report.md:
 *   - schema: required fields, unique ids/words, ranks 1..N, pinyin syllable count matches characters
 *   - every example sentence contains its word
 *   - lists words in each sentence that are ranked after the target (or outside the bank)
 * Exits with code 1 if there are structural errors (not for flagged sentences).
 */
import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { parseCedictLine, isProperNoun, type CedictEntry } from "../lib/cedict";
import { loadFreqTable } from "../lib/wordbank/freq";
import { makeLexicon } from "../lib/wordbank/lexicon";
import { checkExample } from "../lib/wordbank/check-example";
import type { WordBankFile } from "../lib/wordbank/types";

const ROOT = process.cwd();
const bank: WordBankFile = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "words.json"), "utf8"));
const words = bank.words;
const errors: string[] = [];
const warnings: string[] = [];

// Structure
const ids = new Set<number>();
const simps = new Set<string>();
words.forEach((w, i) => {
  const where = `#${i + 1} ${w.simplified}`;
  for (const k of ["id", "simplified", "traditional", "pinyin", "pinyinNum", "meaning", "pos", "hsk", "rank"] as const) {
    if (w[k] === undefined || w[k] === null || w[k] === "") errors.push(`${where}: missing ${k}`);
  }
  if (ids.has(w.id)) errors.push(`${where}: duplicate id ${w.id}`);
  if (simps.has(w.simplified)) errors.push(`${where}: duplicate word`);
  ids.add(w.id);
  simps.add(w.simplified);
  if (w.rank !== i + 1) errors.push(`${where}: rank ${w.rank} should be ${i + 1}`);
  if (Array.from(w.simplified).length !== w.pinyinNum.split(" ").length)
    errors.push(`${where}: ${w.pinyinNum.split(" ").length} syllables for ${Array.from(w.simplified).length} characters`);
  if (Array.from(w.traditional).length !== Array.from(w.simplified).length) warnings.push(`${where}: traditional form length differs`);
  if (w.hsk < 1 || w.hsk > 3) errors.push(`${where}: HSK level ${w.hsk}`);
  if (!/^[a-zü]+[1-5]( [a-zü]+[1-5])*$/.test(w.pinyinNum)) errors.push(`${where}: odd pinyinNum "${w.pinyinNum}"`);
});

// Stroke order data must exist offline for every character in the bank.
const chars = new Set(words.flatMap((w) => Array.from(w.simplified)));
const strokeDir = path.join(ROOT, "node_modules", "hanzi-writer-data");
const noStrokes = [...chars].filter((c) => !fs.existsSync(path.join(strokeDir, `${c}.json`)));
if (!fs.existsSync(strokeDir)) warnings.push("hanzi-writer-data is not installed (run npm install)");
else if (noStrokes.length) errors.push(`no stroke data for: ${noStrokes.join(" ")}`);

// Examples
const cedictFile = fs.readdirSync(path.join(ROOT, "data", "sources")).find((f) => /^cedict.*\.txt\.gz$/.test(f))!;
const cedict = new Map<string, CedictEntry[]>();
for (const line of zlib.gunzipSync(fs.readFileSync(path.join(ROOT, "data", "sources", cedictFile))).toString("utf8").split("\n")) {
  const e = parseCedictLine(line);
  if (e) cedict.set(e.simplified, [...(cedict.get(e.simplified) ?? []), e]);
}
const freq = loadFreqTable();
const rankOf = new Map(words.map((w) => [w.simplified, w.rank]));
const lex = makeLexicon({
  bank: new Map(words.map((w) => [w.simplified, { readings: [w.pinyinNum, ...w.otherReadings.map((r) => r.pinyinNum)], pos: w.pos }])),
  dictWords: new Set(cedict.keys()),
  dictReadings: (x) => {
    const l = cedict.get(x) ?? [];
    return [...l.filter((e) => !isProperNoun(e)), ...l.filter(isProperNoun)].map((e) => e.pinyinNum.toLowerCase());
  },
  freq: (x) => freq.map.get(x) ?? 0,
});

const rows: string[] = [];
let withExample = 0;
let flagged = 0;
for (const w of words) {
  if (!w.example) continue;
  withExample++;
  const c = checkExample(w.example.zh, w, lex, (x) => rankOf.get(x));
  if (!c.containsTarget) errors.push(`#${w.rank} ${w.simplified}: example "${w.example.zh}" does not contain the word`);
  if (!w.example.en) errors.push(`#${w.rank} ${w.simplified}: example has no translation`);
  if (!c.ok) flagged++;
  if (c.later.length || c.outside.length || !c.ok) {
    rows.push(
      `| ${w.rank} | ${w.simplified} | ${w.example.zh} | ${c.later.map((x) => `${x} (#${rankOf.get(x)})`).join(", ")} | ${c.outside.join(", ")} | ${c.ok ? "ok (tolerated)" : "**flagged**: " + c.problems.join("; ")} |`,
    );
  }
}

const report = [
  "# Word bank report",
  "",
  `Generated by \`npm run validate:words\` on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  `- Words: ${words.length}`,
  `- With example sentence: ${withExample} (${words.length - withExample} missing; run \`npm run build:words\` with an OpenRouter key)`,
  `- Flagged sentences: ${flagged}`,
  `- Characters with stroke-order data: ${chars.size - noStrokes.length} of ${chars.size}`,
  `- Structural errors: ${errors.length}, warnings: ${warnings.length}`,
  "",
  "A sentence is fine when it contains its word and uses only words ranked before it. For the first",
  "100 words that is impossible, so up to 2 words from the top 150 are tolerated there.",
  "",
  "## Sentences with later-ranked or outside words",
  "",
  "| Rank | Word | Sentence | Later words | Outside bank | Status |",
  "|---:|---|---|---|---|---|",
  ...rows,
  "",
  ...(errors.length ? ["## Errors", "", ...errors.map((e) => `- ${e}`), ""] : []),
  ...(warnings.length ? ["## Warnings", "", ...warnings.map((e) => `- ${e}`), ""] : []),
].join("\n");
fs.writeFileSync(path.join(ROOT, "data", "words-report.md"), report);

console.log(`${words.length} words, ${withExample} with examples, ${flagged} flagged, ${errors.length} errors, ${warnings.length} warnings.`);
console.log("Report: data/words-report.md");
for (const e of errors.slice(0, 20)) console.log("  ERROR", e);
process.exit(errors.length ? 1 : 0);
